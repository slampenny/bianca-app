for (const [code, patch] of Object.entries(FOLLOWUP)) {
  const file = path.join(GAPS_DIR, `${code}.json`)
  if (!fs.existsSync(file)) {
    console.warn(`skip ${code}: no gap file`)
    continue
  }
  const existing = JSON.parse(fs.readFileSync(file, "utf8"))
  Object.assign(existing, patch)
  fs.writeFileSync(file, JSON.stringify(existing, null, 2) + "\n")
  console.log(`${code}: +${Object.keys(patch).length} follow-up keys`)
}
